/******************************************************************************
 * @brief Set the type of channel
 * 
 * @param ch 
 * @param type 
 * @param sampling_period 
 *****************************************************************************/
static void set_ch_type( int16_t ch, sensor_et type, uint16_t sampling_period )
{
	if( INVALID_CH != ch )
	{
		if( type == AD7124.GetType( ch ) && sampling_period == AD7124.GetSamplePeriod( ch ) )
			return;

		switch( type )
		{
			default:
			case SEN_NONE:
				return;
			case SEN_RTD2X:
				TEMP.Calib[ ch ].pAppl = Calib.data[ ch ].RTD2X;
				TEMP.Calib[ ch ].pAD7124 = Calib.data[ ch ].AD7124[ SEN_RTD2X ];
				break;
			case SEN_RTD:
				TEMP.Calib[ ch ].pAppl = Calib.data[ ch ].RTD;
				TEMP.Calib[ ch ].pAD7124 = Calib.data[ ch ].AD7124[ SEN_RTD ];
				break;
			case SEN_TC_K:
			case SEN_TC_J:
			case SEN_TC_E:
			case SEN_TC_S:
			case SEN_TC_T:
			case SEN_TC_R:
				TEMP.Calib[ ch ].pAppl = Calib.data[ ch ].TC;
				TEMP.Calib[ ch ].pAD7124 = Calib.data[ ch ].AD7124[ SEN_TC_K ];
				break;
			case SEN_COMM:
				return;
		}

		AD7124.SetType( ch, type );
		AD7124.SetSamplePeriod( ch, sampling_period );
		AD7124.ApplyCalibData( ch, TEMP.Calib[ ch ].pAD7124.gain, TEMP.Calib[ ch ].pAD7124.offset );
	}
}

