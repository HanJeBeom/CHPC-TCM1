/******************************************************************************
 * @brief 
 * 
 * @param mV 
 * @param lookup 
 * @param minTemp 
 * @param maxTemp 
 * @param segment 
 * @return float 
 *****************************************************************************/
static float Convert_mV_to_Temp( float mV, const float* lookup, const float minTemp, const float maxTemp, const float segment )
{
	// set up initial values
	int i = NSEG / 2;                   // starting value for 'i' index
	int Add = ( i + 1 ) / 2;                // Add value used in do loop

	// determine if input v is within range
	if ( mV < lookup[ 0 ] )             // if input is under-range..
	{
		i = 0;                        // ..then use lowest coefficients
	}
	else if ( mV >lookup[ NSEG ] )     // if input is over-range..
	{
		i = NSEG - 1;                   // ..then use highest coefficients
	}

	// if input within range, determine which coefficients to use
	else do
	{
		if( lookup[ i ] > mV )  		{ i -= Add; 	} // either decrease i by Add..
		if( lookup[ i + 1 ] < mV ) 		{ i += Add; 	} // ..or increase i by Add
		if( i < 0 )       				{ i = 0;    	} // make sure i is >=0..
		if( i > NSEG - 1 )  			{ i = NSEG - 1; }    // ..and <=NSEG-1
		Add = ( Add + 1 ) / 2;            // divide Add by two (rounded)
	}while( ( lookup[ i ] > mV ) || ( lookup[ i + 1 ] < mV ) );  // repeat 'til done

	return ( minTemp + ( ( maxTemp - minTemp ) / NSEG ) * i + ( mV - lookup[ i ] ) * segment / ( lookup[ i + 1 ] - lookup[ i ] ) );
}

/******************************************************************************
 * @brief LUT calculation
 * 
 * @param input 
 * @param lookup 
 * @param minimum 
 * @param maximum 
 * @param segment 
 * @return float 
 * 
 * @note to find Output from LUT using Intput
 *****************************************************************************/
static float LUT_In_to_Out( float input, const float* lookup, const float minimum, const float maximum, const float segment )
{
	uint16_t idx = ( input - minimum ) / segment;       	// determine which coefficients to use

	if( idx < 0 )               			// if input is under-range..
	{
		idx = 0;                 			// ..then use lowest coefficients
	}
	else if( idx > NSEG - 1 )     		// if input is over-range..
	{
		idx = NSEG - 1;            		// ..then use highest coefficients
	}

	return ( lookup[ idx ] + ( input - ( minimum + segment * idx ) ) * ( lookup[ idx + 1 ] - lookup[ idx ] ) / segment );
}

/******************************************************************************
 * @brief 
 * 
 * @param type 
 * @param Value 
 * @return float 
 * 
 * @note AD7124의 설정이 bipolar이므로 2^n-1로 계산함.
 * Code = 2^(N-1) * ( ( Ain * Gain/2.5) + 1 )
 * Ain = ( Code / 2^(N-1) - 1 ) / Gain * 2.5
 *****************************************************************************/
static float Convert_adc_to_mV( int32_t Value, float sampling_period )
{
	float effectNum = AD7124.GetEffectBit( sampling_period, AD7124_PGA_TC ) * 2; // effectNum = 1/ 2^(N-1)

	Value *= AD7124_BIPOLAR_STEP / effectNum;			// delete ineffective num

	return  (float) Value * effectNum / ( 1 << AD7124_PGA_TC ) * ( TC_VREF_VOLT * 1000.0F );
}

/******************************************************************************
 * @brief 
 * 
 * @param type 
 * @param Value 
 * @param sps 
 * @return float 
 * 
 * @note Rrtd 구하는 방법
	Vrtd := Iexc * Rrtd
	Vref := 2 * Iexc * Rref
	ADC := Vrtd / ( Vref / ADC_GAIN ) * (1 << (ADC_BITDEPTH)) 
	ADC := ( Iexc * Rrtd ) / ( ( 2 * Iexc * Rref ) / ADC_GAIN ) * (1 << (ADC_BITDEPTH)) 
	ADC := Rrtd / ( ( 2 * Rref ) / ADC_GAIN ) * (1 << (ADC_BITDEPTH))
	Rrtd := ( ADC * 2 * Rref  ) / (1 << (ADC_BITDEPTH)) / ADC_GAIN
	ADC_BITDEPTH = 24bit -1(differential) - 5.7(무효bit) = 17.3bit
 *****************************************************************************/
static float Convert_adc_to_Resistor( sensor_et type, uint32_t Value, float sampling_period )
{
	uint8_t PgaGain;
	float effectNum;

	if( type == SEN_RTD2X )
	{
		PgaGain = 1 << AD7124_PGA_2X_RTD;
		effectNum = AD7124.GetEffectBit( sampling_period, AD7124_PGA_2X_RTD );
	}
	else
	{
		PgaGain = 1 << AD7124_PGA_RTD;
		effectNum = AD7124.GetEffectBit( sampling_period, AD7124_PGA_RTD );
	}

	Value *= AD7124_UNIPOLAR_STEP / effectNum;			// delete ineffective num
	return Value * ( 2 * RTD_CIRCUIT_R_REF * effectNum / PgaGain );
}

/******************************************************************************
 * @brief 
 * 
 * @param type 
 * @param ch 
 * @param ConvertValue 
 * @param MaxSection 
 * @return float 
 *****************************************************************************/
static float calibrate_temp( uint8_t ch, float ConvertValue, const int MaxSection )
{
	uint8_t index = MaxSection - 1;
	int32_t rawValue = AD7124.GetValue( ch );

	for( uint8_t i = 0; i < MaxSection; i++ )
	{
		if( rawValue <= TEMP.Calib[ ch ].pAppl[ i ].boundary )
		{
			index = i;
			break;
		}
	}
	return ( ( ConvertValue - TEMP.Calib[ ch ].pAppl[ index ].offset ) * TEMP.Calib[ ch ].pAppl[ index ].gain );
}

/******************************************************************************
 * @brief 
 * 
 * @param type 
 * @param ch 
 * @param ColdJTemp 
 * @return float 
 *****************************************************************************/
static float TC_Conversion( sensor_et type, uint8_t ch, float ColdJTemp )
{
	float result = 0.0f;
	float CJ_mV = 0.0f;
	float HJ_mV = calibrate_temp( ch, Convert_adc_to_mV( AD7124.GetValue( ch ), AD7124.GetSamplePeriod( ch ) ), CALIB_TC_SECTION );

	switch( type )
	{
		default:
		case SEN_TC_K:
			CJ_mV = LUT_In_to_Out( ColdJTemp, LUT_TC_K_Temp_to_mV, TMIN_K, TMAX_K, TSEG_K );
			result = Convert_mV_to_Temp( HJ_mV + CJ_mV, LUT_TC_K_Temp_to_mV, TMIN_K, TMAX_K, TSEG_K );
			break;
		case SEN_TC_J:
			CJ_mV = LUT_In_to_Out( ColdJTemp, LUT_TC_J_Temp_to_mV, TMIN_J, TMAX_J, TSEG_J );
			result = Convert_mV_to_Temp( HJ_mV + CJ_mV, LUT_TC_J_Temp_to_mV, TMIN_J, TMAX_J, TSEG_J );
			break;
		case SEN_TC_E:
			CJ_mV = LUT_In_to_Out( ColdJTemp, LUT_TC_E_Temp_to_mV, TMIN_E, TMAX_E, TSEG_E );
			result = Convert_mV_to_Temp( HJ_mV + CJ_mV, LUT_TC_E_Temp_to_mV, TMIN_E, TMAX_E, TSEG_E );
			break;
		case SEN_TC_S:
			CJ_mV = LUT_In_to_Out( ColdJTemp, LUT_TC_S_Temp_to_mV, TMIN_S, TMAX_S, TSEG_S );
			result = Convert_mV_to_Temp( HJ_mV + CJ_mV, LUT_TC_S_Temp_to_mV, TMIN_S, TMAX_S, TSEG_S );
			break;
		case SEN_TC_T:
			CJ_mV = LUT_In_to_Out( ColdJTemp, LUT_TC_T_Temp_to_mV, TMIN_T, TMAX_T, TSEG_T );
			result = Convert_mV_to_Temp( HJ_mV + CJ_mV, LUT_TC_T_Temp_to_mV, TMIN_T, TMAX_T, TSEG_T );
			break;
		case SEN_TC_R:
			break;
	}
	
	return result;
}

