typedef union tcn75a_status_union_Tag {
	struct {
		uint16_t initiated : 1;
		uint16_t resolution : 2;
	};

	uint16_t All;
} tcn75a_status_ut;

typedef enum tcn75a_resolution_enum_Tag {
    TCN75A_CFG_RESOULTION_9 = 0x00,
    TCN75A_CFG_RESOULTION_10 = 0x20,
    TCN75A_CFG_RESOULTION_11 = 0x40,
    TCN75A_CFG_RESOULTION_12 = 0x60
} tcn75a_resolution_et;

typedef struct TCN75A_struct_Tag {
    void (*SetResolution)( tcn75a_resolution_et resolution );   // @param[in] ADC resoultion bit / 9bit => 0.5ºC, 10bit => 0.25ºC, 11bit => 0.125ºC, 12bit => 0.0625ºC
    float (*GetTemperature)( void );                            // @returns the current temperature of the cold junction in degrees Celsius.

    tcn75a_status_ut *Status;
} TCN75A_st;

