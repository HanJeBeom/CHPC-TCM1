/*****************************************************************************/
/** DATATYPES ****************************************************************/
/*****************************************************************************/

typedef struct adc_cj_instance_Tag
{
	float cj_mVoltage;
	struct
	{
		float voltage;
		float temp;
	} IC_temp;
} adc_cj_instance_st;

/*****************************************************************************/
/** FUNCTION DECLARATIONS ****************************************************/
/*****************************************************************************/

static void adc_start( void );
static void adc_stop( void );
static float adc_get_temp( uint8_t idx );

/*****************************************************************************/
/** EXTERNAL VARIABLES *******************************************************/
/*****************************************************************************/

extern ADC_HandleTypeDef hadc1;
extern DMA_HandleTypeDef hdma_adc1;

/*****************************************************************************/
/** LOCAL VARIABLES **********************************************************/
/*****************************************************************************/

static uint16_t adc_buf[ 1 ] = { 0 };
static adc_cj_instance_st adc_data;

/*****************************************************************************/
/** GLOBAL VARIABLES *********************************************************/
/*****************************************************************************/

const ADC_MCU_st ADC_MCU =
{
	.Start = adc_start,
	.Stop = adc_stop,
	.GetTemp = adc_get_temp,
};

/*****************************************************************************/
/** FUNCTION DEFINITIONS *****************************************************/
/*****************************************************************************/

/******************************************************************************
 * @brief
 *
 *****************************************************************************/
static void adc_start( void )
{
	HAL_ADC_Start_DMA( &hadc1, ( uint32_t* )adc_buf, 1 );
}

/******************************************************************************
 * @brief
 *
 *****************************************************************************/
static void adc_stop( void )
{
	HAL_ADC_Stop_DMA( &hadc1 );
}

/******************************************************************************
 * @brief
 *
 * @param idx
 * @return
 *****************************************************************************/
static float adc_get_temp( uint8_t idx )
{
	float temp = 0.0f;

	switch( idx )
	{
		case 0:
			temp = adc_data.IC_temp.temp;
			break;

		default:
			temp = -300.0f;
			break;
	}

	return temp;
}

/******************************************************************************
 * @brief Low Pass Filter
 * 
 * @param input input data
 * @param fc cut-off frequency
 * @param fs sampling frequency
 * @return float filtered data
 *****************************************************************************/
float lpf(float input, float prev_output, float fc, float fs)
{
	float output;

	float alpha = 2 * 3.1415926535f * fc / fs;

	if( alpha > 1.0f )
	{
		alpha = 1.0f;
	}

	output = alpha * input + ( 1 - alpha ) * prev_output;

	return output;
}

/******************************************************************************
 * @brief
 *
 * @param hadc
 *****************************************************************************/
void HAL_ADC_ConvCpltCallback( ADC_HandleTypeDef *hadc )
{
	// MCU Temperature Sensor
	adc_data.IC_temp.voltage = 3.3f * adc_buf[ 0 ] / ( 1 << 12 );
	adc_data.IC_temp.temp = lpf(( adc_data.IC_temp.voltage - 0.76f ) / 0.0025f + 25.0f, adc_data.IC_temp.temp, 1, 45000);
}
